// Verified, independently authored source banks -> offline classic-script data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const gameRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const folder = path.join(gameRoot, 'docs/design/features/town-dialogue');
const questions = ['quiz-science.json', 'quiz-culture.json'].flatMap((name) => JSON.parse(fs.readFileSync(path.join(folder, name), 'utf8')));
questions.sort((a, b) => a.id.localeCompare(b.id));
if (questions.length !== 50) throw new Error('The verified quiz bank must contain exactly 50 questions.');
for (const [index, q] of questions.entries()) {
  const expected = `quiz${String(index + 1).padStart(2, '0')}`;
  if (q.id !== expected || ![1, 2, 3].includes(q.level)) throw new Error(`Invalid question identity: ${q.id}`);
  if (!q.topic || !q.prompt || !q.explanation || !Array.isArray(q.choices) || q.choices.length < 3 || q.choices.length > 5 || new Set(q.choices).size !== q.choices.length) throw new Error(`Invalid question text: ${q.id}`);
  if (!Number.isInteger(q.answer) || q.answer < 0 || q.answer >= q.choices.length) throw new Error(`Invalid answer: ${q.id}`);
  if (!Array.isArray(q.sources) || new Set(q.sources.map((s) => s.url)).size < 2 || q.sources.some((s) => !s.title || !s.evidence || !/^\d{4}-\d{2}-\d{2}$/.test(s.checked) || new URL(s.url).protocol !== 'https:')) throw new Error(`Missing verified sources: ${q.id}`);
}
const output = `// Generated by node tools/build-town-quiz.mjs. Edit the two verified JSON source banks.\nconst TOWN_QUIZ_DATA = ${JSON.stringify(questions, null, 2)};\n`;
const dest = path.join(gameRoot, 'js/town-quiz-data.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('town-quiz-data.js is stale; run node tools/build-town-quiz.mjs.');
} else fs.writeFileSync(dest, output, 'utf8');
console.log(`Town quiz: ${questions.length} verified questions; levels ${[1, 2, 3].map((l) => questions.filter((q) => q.level === l).length).join('/')}.`);
